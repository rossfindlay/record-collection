import { type NextRequest } from "next/server";
import { proxy } from "../_proxy";

export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ path: string[] }> },
) {
  const { path } = await params;
  return proxy(request, `/api/user/${path.join("/")}`);
}

